// Package outbox — PATTERN: transactional outbox.
//
// Проблема, которую он решает: бизнес-изменение (например, «фото создано»)
// и публикация события об этом факте — это ДВЕ разные системы (PostgreSQL
// и Kafka), и написать в обе одной транзакцией нельзя. Если сначала
// закоммитить строку в Postgres, а потом отправить в Kafka, процесс может
// упасть между этими шагами — и снаружи будет казаться, что фото есть,
// а событие об этом никто никогда не получит. Сделать наоборот (сначала
// Kafka) — ещё хуже: событие уйдёт, а транзакция в Postgres может
// откатиться, и подписчики отреагируют на факт, которого не было.
//
// Решение: событие пишется в СВОЮ таблицу (outbox) В ТОЙ ЖЕ транзакции,
// что и бизнес-изменение (Write, outbox.go). Раз это одна транзакция
// в одной базе — атомарность бесплатна, её даёт сам Postgres. Отдельный
// процесс (Relay, relay.go) вычитывает неопубликованные строки и уже
// САМ публикует их в Kafka, отмечая опубликованные.
//
// Чего в пакете сознательно нет:
//   - удаления опубликованных строк. Таблица растёт, и чистка (по
//     published_at старше N дней) — обязанность вызывающего сервиса
//     (cron/партиционирование), а не этого пакета: у него нет доступа
//     к политике хранения конкретного сервиса;
//   - ровно однократной доставки. Between produce и update относительно
//     Kafka всё ещё есть окно: если relay упадёт ПОСЛЕ успешного produce,
//     но ДО update published_at, строка при перезапуске уйдёт в Kafka
//     ПОВТОРНО. Это тот же at-least-once, что и у остального проекта —
//     см. docs/adr/0008-*, раздел «чем платим», и интеграционный тест
//     relay_integration_test.go, который эту ситуацию воспроизводит.
package outbox

import "time"

// OutboxRow — строка таблицы outbox.
//
// Отдельный тип, а не переиспользование eventsv1.Envelope: строка таблицы —
// это ещё и служебные поля (published_at, created_at), которых в контракте
// событий нет и быть не должно, а Payload здесь — уже СЕРИАЛИЗОВАННЫЙ
// Envelope (готовый к отправке в Kafka как есть), а не структура для
// повторного маршалинга при каждом чтении.
type OutboxRow struct {
	// ID — UUID v7, тот же, что в поле event_id конверта: первые 48 бит —
	// unix-время, поэтому вставка всегда идёт в «правый край» индекса
	// (см. тот же довод в pkg/kafkax.newEventID). Для relay это ещё и
	// готовый порядок публикации: ORDER BY id эквивалентен ORDER BY время.
	ID string `gorm:"type:uuid;primaryKey"`

	// AggregateID нужен ИНДЕКСОМ, а не только для чтения: типичный вопрос
	// поддержки — «что там с событиями агрегата X» — не должен требовать
	// разбора Payload у всей таблицы.
	AggregateID string `gorm:"column:aggregate_id;not null;index"`

	// Topic и Key relay использует напрямую при публикации — ему не нужно
	// (и не должно быть нужно) знать соглашение об именовании топиков
	// или откуда берётся ключ партиционирования, это знание уже
	// зафиксировано на момент Write.
	Topic string `gorm:"not null"`
	Key   []byte `gorm:"not null"`

	// Headers — JSON-объект строка→строка (event_id, event_type,
	// traceparent, ...), сохранённый КАК ЕСТЬ в момент Write. Почему не
	// пересобирать заголовки заново в relay — см. комментарий в outbox.go
	// у функции Write: traceparent берётся из контекста ИСХОДНОГО запроса,
	// а у relay спустя секунды или минуты своего контекста для этого уже нет.
	Headers []byte `gorm:"type:jsonb;not null;default:'{}'"`

	// Payload — уже сериализованный proto.Marshal(Envelope). Не пересобираем
	// Any/Envelope из отдельных колонок: тогда relay пришлось бы знать все
	// типы событий проекта, а сейчас он ими не интересуется вовсе.
	Payload []byte `gorm:"type:bytea;not null"`

	CreatedAt time.Time `gorm:"not null;default:now();index"`

	// PublishedAt — NULL, пока relay не подтвердит публикацию. Это и есть
	// признак «в очереди», на нём построен весь SELECT relay'я
	// (WHERE published_at IS NULL).
	PublishedAt *time.Time
}

// TableName — имя по умолчанию. Реальное имя таблицы у каждого сервиса своё
// и строится через TableFor: см. комментарий к ней.
func (OutboxRow) TableName() string { return "outbox" }

// TableFor — имя таблицы outbox для сервиса: "outbox_media", "outbox_catalog".
//
// Таблица у каждого сервиса СВОЯ, и это не педантизм. В gosplash media и
// thumbnail-worker делят одни и те же шарды PostgreSQL (docs/adr/0002-*:
// отметка об обработке и строка фото обязаны лежать в одной транзакции,
// а значит и в одной базе). С одной общей таблицей outbox над ней крутились
// бы ДВА relay, и получалось бы следующее:
//
//   - relay стоит перед строкой, которую записал не он, и не может сказать,
//     кто её автор. Заголовок producer — это ответ на вопрос «кто прислал
//     это сообщение», и он обязан быть правдой;
//   - метрика outbox_pending{service} считала бы одни и те же строки дважды,
//     под двумя разными именами сервиса. На ней построен алерт.
//
// Разделение по таблицам убирает обе проблемы и заодно возвращает простое
// правило: у процесса, который публикует события, есть своя очередь, и
// никто в неё больше не пишет.
func TableFor(service string) string { return "outbox_" + sanitizeIdent(service) }

// sanitizeIdent превращает имя сервиса в безопасный идентификатор SQL:
// всё, кроме латиницы, цифр и подчёркивания, становится подчёркиванием.
//
// Это не косметика, а исправление настоящей аварии. Имя "thumbnail-worker"
// давало таблицу outbox_thumbnail-worker, и PostgreSQL читал дефис как
// ОПЕРАТОР ВЫЧИТАНИЯ: «outbox_thumbnail минус worker» → syntax error at
// or near "-". Причём GORM при создании таблицы имя кавычил и таблицу
// создавал успешно, а сырой SQL релея — нет, так что ломался только один
// из двух путей, и только в рантайме.
//
// Второе следствие важнее первого: имя таблицы подставляется в SQL строкой,
// а не параметром (параметры бывают только у значений, не у идентификаторов).
// Пока имя приходит из константы в main.go, это безопасно; но функция
// публичная, и единственная честная защита — не полагаться на дисциплину
// вызывающего, а привести имя к заведомо безопасному виду здесь.
func sanitizeIdent(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_':
			out = append(out, r)
		case r >= 'A' && r <= 'Z':
			// PostgreSQL складывает некавыченные идентификаторы в нижний
			// регистр. Делаем это сами, чтобы TableFor возвращал ровно то
			// имя, которое окажется в базе.
			out = append(out, r+('a'-'A'))
		default:
			out = append(out, '_')
		}
	}
	return string(out)
}
