package kafkax

import (
	"math/rand/v2"
	"time"
)

// MaxRetryAttempts — сколько раз Handler пробует обработать сообщение
// «на месте» (в текущей горутине партиции), прежде чем оно уедет
// в <topic>.retry.
//
// Три — компромисс, а не круглое число для красоты: меньше, и
// кратковременная просадка соседнего сервиса (перезапуск пода, GC-пауза)
// уже гонит сообщения в retry-топик, раздувая его пустыми повторами. Больше —
// партиция дольше стоит на одном сообщении, пока сосед не восстановится,
// а остальные события той же партиции (в том числе других агрегатов) ждут
// вместе с ним.
const MaxRetryAttempts = 3

const (
	// backoffBase — задержка перед второй попыткой (первая — без задержки).
	backoffBase = 200 * time.Millisecond
	// backoffCap — потолок, дальше экспонента не растёт. Без потолка
	// несколько дополнительных «раундов» в retry-топике (см. retry.go)
	// увели бы задержку в часы одним лишним битом сдвига.
	backoffCap = 30 * time.Second
)

// Backoff — экспоненциальная задержка с ПОЛНЫМ jitter перед попыткой attempt
// (нумерация с 1: Backoff(1) — задержка перед второй попыткой).
//
// Полный jitter — это НЕ «экспонента ± немного», а равномерная случайная
// величина от нуля до экспоненты. Смысл: если ошибка одновременно поймали
// несколько партиций (например, все — сетевой сбой до одного и того же
// зависимого сервиса), частичный jitter всё равно оставляет их синхронными
// по фазе, и повторные попытки бьют по восстанавливающемуся сервису волнами
// той же частоты, что и исходный сбой. Полный jitter размазывает повторы
// равномерно по всему окну и волну гасит.
//
// Экспортирована и вынесена в чистую функцию без побочных эффектов, чтобы
// её можно было проверить в тесте на свойства (монотонная верхняя граница,
// потолок, детерминированный случай attempt<1), не поднимая ни консьюмера,
// ни тем более Kafka.
func Backoff(attempt int) time.Duration {
	if attempt < 1 {
		attempt = 1
	}

	// 1<<63 переполнил бы int64 уже на скромном attempt — потолок проверяем
	// по количеству сдвигов, а не по результату умножения.
	const maxShift = 20 // 200ms * 2^20 ≈ 58 часов, с огромным запасом выше backoffCap
	shift := attempt - 1
	if shift > maxShift {
		shift = maxShift
	}

	exp := backoffBase * time.Duration(uint64(1)<<uint(shift))
	if exp > backoffCap {
		exp = backoffCap
	}

	// rand.Int64N паникует на n<=0; exp здесь всегда положителен (backoffBase>0).
	return time.Duration(rand.Int64N(int64(exp) + 1))
}
