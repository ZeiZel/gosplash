// Package resilience — два независимых механизма устойчивости к сбоям
// нижестоящих сервисов, и их сознательно НЕ стоит путать между собой:
//
//	Retry (retry.go)     — лечит МГНОВЕННЫЙ, единичный сбой: пакет потерялся,
//	                       под перезапускался долю секунды, балансировщик
//	                       на секунду отправил запрос в под, который ещё не
//	                       успел принять трафик. Ответ — попробовать ещё раз,
//	                       и почти наверняка сработает.
//	Breaker (breaker.go) — лечит ЗАТЯЖНОЙ сбой: сервис не отвечает уже
//	                       секунды и минуты (упал, деплоится, зациклился на
//	                       блокировке в базе). Ретраить здесь вредно: каждая
//	                       попытка держит горутину и соединение на полный
//	                       таймаут, и вместо одного медленного запроса
//	                       вызывающий сервис копит их сотнями, пока сам не
//	                       ляжет от исчерпания пула. Правильный ответ —
//	                       перестать ходить в мёртвый сервис вовсе и
//	                       отвечать мгновенно, пока он не подаст признаков
//	                       жизни.
//
// Оба механизма работают вместе (см. pkg/grpcx.Dial), но решают РАЗНЫЕ
// задачи и держат РАЗНОЕ состояние: retry ничего не помнит между вызовами,
// breaker помнит статистику отказов и меняет поведение всех последующих
// вызовов, пока не увидит признаков восстановления.
//
// Чего в пакете сознательно нет: ретраев неидемпотентных операций. Это не
// упущение, а запрет, закреплённый в самом API (см. комментарий к
// NewRetrier) — повторный вызов «списать деньги» после сетевой ошибки
// (когда неизвестно, ушло списание или нет) означает риск списать дважды.
