package redisx

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/google/uuid"
	"github.com/redis/go-redis/v9"
)

// PATTERN: распределённый лок SET NX PX + токен + Lua-release + watchdog.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ, и это важнее самого кода: этот лок — ОПТИМИЗАЦИЯ
// («скорее всего, эту работу сейчас делает только один воркер»), а не
// гарантия взаимного исключения. Он ломается минимум в двух реальных
// сценариях:
//
//  1. Сетевое разделение. Воркер A держит лок, у него на секунду отваливается
//     сеть до Redis. TTL истекает, Redis отдаёт лок воркеру B. Воркер B
//     начинает работу. Тут сеть у A восстанавливается, и A — который всё ещё
//     считает себя владельцем лока, — продолжает ту же работу параллельно
//     с B. Оба воркера активны одновременно ровно то время, в которое лок
//     должен был гарантировать обратное.
//  2. Пауза GC (или планировщика ОС) внутри критической секции. Процесс A
//     держит лок, останавливается на STW-паузе дольше TTL, Redis отдаёт лок
//     B, A просыпается и как ни в чём не бывало продолжает работу — с его
//     точки зрения между «взял лок» и «текущей строкой кода» не прошло
//     времени, потому что процесс не выполнялся.
//
// В обоих случаях сверка токена в Unlock защищает только от того, чтобы A
// не снял ЧУЖОЙ (уже принадлежащий B) лок при попытке освободить свой — она
// НЕ защищает от того, что A и B одновременно выполняют работу. Watchdog
// снижает вероятность false expiry (лок продлевается, пока работа реально
// идёt), но не может продлевать лок во время самой паузы GC — это тот же
// процесс и тот же поток исполнения, что и код, который эту паузу вызвал.
//
// Поэтому в проекте единственная НАСТОЯЩАЯ гарантия «эта работа выполнена
// ровно один раз» — идемпотентность на стороне обработчика через
// processed_events (fencing по event_id), а не факт владения локом. Лок
// здесь нужен только чтобы в общем случае не делать одну и ту же дорогую
// работу (генерацию превью) дважды одновременно — не чтобы это было
// невозможно в принципе. Подробнее и почему это осознанный выбор, а не
// недоработка — в docs/adr/0012-redis-lock-protiv-advisory-lock.md.
type Lock struct {
	c     *Client
	key   string
	token string
	ttl   time.Duration

	stop     chan struct{}
	watchdog chan struct{} // закрывается, когда горутина watchdog'а завершилась
}

// unlockScript снимает лок, только если он всё ещё принадлежит вызывающему.
//
// Без сверки токена unlock превращается в баг с полным правом на данные
// другого процесса: если лок A истёк по TTL, Redis уже отдал его B, а A
// (не зная об этом) в конце своей работы вызывает `DEL key` без проверки —
// он снимает лок B, а не свой. С этого момента ДВА следующих претендента
// на лок оба решат, что путь свободен, и защита пропадёт полностью именно
// в тот момент, когда лок якобы истёк по «нормальной» причине (перегруз, а
// не сетевой сбой), то есть в самый частый сценарий состязания.
//
// Удаление — UNLINK, а не DEL, тем же правилом, что и в cache.go: не
// блокировать однопоточный Redis на освобождении памяти. Для лока (пара
// байт) разница на практике незаметна, но правило в проекте одно на все
// случаи, а не «DEL, если объект маленький».
const unlockScript = `
if redis.call('GET', KEYS[1]) == ARGV[1] then
	return redis.call('UNLINK', KEYS[1])
else
	return 0
end
`

// extendScript продлевает TTL лока, только если он всё ещё принадлежит
// вызывающему — той же сверкой, что и unlockScript, и по той же причине:
// продлить чужой (уже перехваченный кем-то) лок так же плохо, как снять его.
const extendScript = `
if redis.call('GET', KEYS[1]) == ARGV[1] then
	return redis.call('PEXPIRE', KEYS[1], ARGV[2])
else
	return 0
end
`

var (
	unlock = redis.NewScript(unlockScript)
	extend = redis.NewScript(extendScript)
)

// watchdogInterval — как часто продлевать лок относительно его TTL.
// Треть TTL — компромисс: реже — рискуем не успеть продлить при недолгой
// задержке сети (одна неудачная попытка не должна стоить лока); чаще —
// лишняя нагрузка на Redis без выигрыша в надёжности.
const watchdogFraction = 3

// Acquire пытается взять лок key на ttl. Если лок уже занят, возвращает
// (nil, nil) — это не ошибка, это нормальный проигрыш в гонке за лок;
// вызывающий сам решает, ждать ли повторной попытки.
//
// При успехе запускает watchdog: горутину, которая продлевает TTL, пока
// работа не завершится через Unlock или пока не отменится ctx (тот же ctx,
// что был передан сюда, — то есть время жизни лока ограничено временем жизни
// вызывающей операции, а не отдельным таймером).
func (c *Client) Acquire(ctx context.Context, key string, ttl time.Duration) (*Lock, error) {
	token := uuid.NewString()

	ok, err := c.rdb.SetNX(ctx, key, token, ttl).Result()
	if err != nil {
		return nil, fmt.Errorf("redisx: acquire %q: %w", key, err)
	}
	if !ok {
		return nil, nil
	}

	l := &Lock{
		c:        c,
		key:      key,
		token:    token,
		ttl:      ttl,
		stop:     make(chan struct{}),
		watchdog: make(chan struct{}),
	}
	go l.runWatchdog(ctx)
	return l, nil
}

func (l *Lock) runWatchdog(ctx context.Context) {
	defer close(l.watchdog)

	interval := l.ttl / watchdogFraction
	if interval <= 0 {
		// Защита от паники NewTicker на слишком коротком TTL — на практике
		// лок с TTL меньше нескольких десятков миллисекунд смысла не имеет
		// (одна сетевая операция может занять больше), но упасть здесь
		// хуже, чем взять минимальный разумный интервал.
		interval = 10 * time.Millisecond
	}
	ticker := time.NewTicker(interval)
	defer ticker.Stop()

	for {
		select {
		case <-l.stop:
			return
		case <-ctx.Done():
			return
		case <-ticker.C:
			// Собственный контекст с таймаутом, а не ctx вызывающего: если
			// ctx вот-вот отменится, продление всё равно должно успеть
			// выполниться (или честно не успеть) за разумное время, а не
			// зависнуть до отмены родителя — иначе watchdog не сможет вовремя
			// заметить следующий тик и лок протухнет раньше времени.
			extendCtx, cancel := context.WithTimeout(context.Background(), interval)
			_, err := extend.Run(extendCtx, l.c.rdb, []string{l.key}, l.token, l.ttl.Milliseconds()).Result()
			cancel()
			if err != nil && !errors.Is(err, redis.Nil) {
				// Не смогли продлить — лок может протухнуть раньше, чем
				// работа завершится. Это ровно тот случай, который делает
				// лок оптимизацией, а не гарантией (см. doc-комментарий Lock):
				// вызывающий узнает об этом только по неудаче Unlock ниже.
				return
			}
		}
	}
}

// Unlock останавливает watchdog и снимает лок, если он всё ещё наш.
//
// Возвращает ошибку, если лок к этому моменту уже не принадлежал нам
// (протух и был перехвачен) — вызывающий обязан считать это сигналом, что
// его работа могла выполняться параллельно с кем-то ещё, и не полагаться
// на эксклюзивность постфактум.
func (l *Lock) Unlock(ctx context.Context) error {
	close(l.stop)
	<-l.watchdog

	res, err := unlock.Run(ctx, l.c.rdb, []string{l.key}, l.token).Int64()
	if err != nil {
		return fmt.Errorf("redisx: unlock %q: %w", l.key, err)
	}
	if res == 0 {
		return fmt.Errorf("redisx: unlock %q: лок уже не наш — истёк и был перехвачен другим владельцем", l.key)
	}
	return nil
}
