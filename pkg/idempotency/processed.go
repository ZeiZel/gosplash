// Package idempotency — защита от повторной обработки события.
//
// PATTERN: idempotent consumer. Kafka даёт at-least-once: сообщение
// обработается минимум один раз, но может и дважды — процесс умер между
// успешной работой и коммитом offset'а, случился ребаланс, кто-то переиграл
// топик из DLQ. Обработчик обязан пережить повтор.
//
// Есть два способа это обеспечить, и выбирать между ними нужно осознанно:
//
//	Естественная идемпотентность — когда повтор безопасен сам по себе.
//	  Upsert карточки в каталоге таков: записать то же состояние второй раз
//	  ничего не меняет. Это самый дешёвый вариант, и пока он работает,
//	  ничего больше не нужно.
//
//	Таблица обработанных событий — когда не работает. «Сделать превью» —
//	  это лишняя работа процессора и лишние объекты в S3; «списать деньги» —
//	  это двойное списание. Здесь нужна явная отметка.
//
// Ключевое условие корректности: отметка вставляется В ТОЙ ЖЕ ТРАНЗАКЦИИ,
// что и бизнес-изменение. Разнесёшь их — и появится окно, в котором работа
// сделана, а отметки нет (или наоборот), то есть ровно та проблема,
// которую отметка и должна была убрать.
//
// Вместе с at-least-once это даёт effectively-once: событие может приехать
// сколько угодно раз, но применится ровно один. Настоящий exactly-once
// в распределённой системе недостижим, и его всегда заменяют этой парой.
package idempotency

import (
	"fmt"
	"time"

	"gorm.io/gorm"
	"gorm.io/gorm/clause"
)

// ProcessedEvent — строка таблицы processed_events.
//
// Сервисы включают её в свой AutoMigrate. Таблица у каждого сервиса своя:
// «обработано» — это утверждение конкретного консьюмера о конкретном
// событии, и общая таблица на всех означала бы, что один сервис отменяет
// работу другого.
type ProcessedEvent struct {
	// EventID приходит из конверта события. UUID v7, поэтому вставки идут
	// в «правый край» B-tree, а не в случайную страницу.
	EventID string `gorm:"primaryKey;size:64"`

	// Тип и тема — только для разбора инцидентов: по таблице должно быть
	// видно, что именно уже применено.
	EventType string `gorm:"size:128;index"`
	Topic     string `gorm:"size:128"`

	ProcessedAt time.Time `gorm:"index"`
}

func (ProcessedEvent) TableName() string { return "processed_events" }

// Claim помечает событие обработанным и говорит, надо ли его обрабатывать.
//
// Возвращает true — событие видится впервые, вызывающий продолжает работу
// В ЭТОЙ ЖЕ транзакции. Возвращает false — событие уже применено, работу
// нужно пропустить, а offset всё равно закоммитить.
//
// Вызывается ПЕРВЫМ действием транзакции, до бизнес-изменений. Порядок важен
// не для корректности (транзакция атомарна в любом случае), а для стоимости:
// на повторе не будет сделано ни одного лишнего запроса.
//
// ON CONFLICT DO NOTHING вместо «сначала SELECT, потом INSERT» — потому что
// проверка и вставка двумя запросами это гонка: два консьюмера одного
// события (ребаланс успел передать партицию, пока первый ещё работал)
// оба увидят «нет такого» и оба начнут работать. Один атомарный INSERT
// такого окна не оставляет — проигравший получит RowsAffected == 0.
func Claim(tx *gorm.DB, eventID, eventType, topic string) (bool, error) {
	if eventID == "" {
		// Событие без идентификатора дедуплицировать нечем. Это не «можно
		// обработать разок», а сломанный контракт: конверт обязан нести
		// event_id. Молча пропустить такое — значит получить двойную
		// обработку в самом неожиданном месте.
		return false, fmt.Errorf("idempotency: пустой event_id")
	}

	result := tx.Clauses(clause.OnConflict{DoNothing: true}).Create(&ProcessedEvent{
		EventID:     eventID,
		EventType:   eventType,
		Topic:       topic,
		ProcessedAt: time.Now(),
	})
	if result.Error != nil {
		return false, fmt.Errorf("idempotency: отметка события %s: %w", eventID, result.Error)
	}

	// RowsAffected == 0 означает, что строка уже была: конфликт по
	// первичному ключу, вставка не выполнена.
	return result.RowsAffected > 0, nil
}

// Forget удаляет отметку. Нужен ровно в одном сценарии: событие переигрывают
// намеренно после того, как починили причину сбоя, — например, превью
// сгенерировались битыми из-за ошибки в коде, и их надо сделать заново.
//
// В обычной работе не используется никогда. Если он понадобился в
// production-пути, значит, идемпотентность пытаются применить не туда.
func Forget(db *gorm.DB, eventID string) error {
	if err := db.Delete(&ProcessedEvent{}, "event_id = ?", eventID).Error; err != nil {
		return fmt.Errorf("idempotency: снятие отметки %s: %w", eventID, err)
	}
	return nil
}
