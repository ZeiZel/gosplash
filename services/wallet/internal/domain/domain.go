// Package domain — предметная область кошелька: счета, проводки, резервы.
//
// Здесь сознательно нет ничего, что было бы должно только адаптерам:
// ни тегов gorm/json/protobuf, ни импортов gorm/grpc/gen. Domain отвечает
// на вопрос «что такое деньги в этой системе», а не «как их положить в
// PostgreSQL» — эти вопросы разведены по разным пакетам (internal/adapters),
// см. docs/STYLE.md, «Раскладка сервиса».
//
// PATTERN: двойная запись (double-entry bookkeeping). Каждая денежная
// операция — это ДВЕ проводки, дебет одного счёта и кредит другого, в одной
// транзакции, на одну и ту же сумму. Из этого следует главный инвариант
// системы: сумма amount_cents по ВСЕМ проводкам ВСЕХ счетов всегда равна
// нулю — деньги никогда не появляются и не исчезают, они только
// переезжают с одного счёта на другой. Это же и есть способ проверить
// целостность всей истории ОДНИМ запросом (см. mk/wallet.mk, wallet-check):
// SELECT SUM(...) равный нулю — это математическое доказательство того, что
// ни одна проводка не была создана в одиночку, без парной.
//
// Колонка balance, которую инкрементируют при каждой операции, такой
// проверки не даёт вообще: она хранит ТЕКУЩЕЕ число, а не историю, из
// которой оно получилось, и баг вида «списали, а зачислить забыли» в ней
// неотличим от корректного состояния — оба выглядят как обычное число.
// Здесь баланс — это ВЫЧИСЛЯЕМЫЙ агрегат (сумма проводок), а не поле,
// которое можно испортить одной некорректной операцией записи в обход
// парного правила.
//
// ledger_entries — APPEND-ONLY. UPDATE и DELETE по ней запрещены: история
// операций неизменяема, потому что это и есть бухгалтерская книга, а не
// кэш текущего состояния. Исправление ошибочной проводки — это НОВАЯ
// проводка, которая её компенсирует (сторно), а не правка задним числом.
// Позволить UPDATE — значит разрешить переписывать прошлое, после чего
// инвариант «сумма равна нулю» перестаёт что-либо доказывать: он был бы
// верен и для книги, которую подделали.
package domain

import "time"

// Money — сумма в минимальных единицах валюты (копейках) плюс код валюты.
//
// Только целые копейки, int64, никогда float. 0.1 + 0.2 в double не равно
// 0.3 — ошибка на уровне последнего бита мантиссы, которая на балансе
// счёта рано или поздно всплывает расхождением в копейку, необъяснимым
// без разбора конкретных операций с точностью до бита. int64 копеек такой
// проблемы не имеет вообще: сложение и вычитание целых чисел в Go точны,
// пока сумма не переполняет диапазон (для учебного проекта — не предел).
// Валюта хранится РЯДОМ отдельным полем и никогда не подразумевается:
// сумма без валюты — это не сумма (proto/gosplash/wallet/v1/wallet.proto,
// комментарий к Money — тот же довод, домен и контракт согласованы
// намеренно).
type Money struct {
	AmountCents int64
	Currency    string
}

// Направления проводки. Строкой, а не bool ("is_credit"): в отчётах
// и в SQL-запросах debit/credit читается сразу, а true/false требует
// подглядывать в код, что есть что.
const (
	DirectionDebit  = "debit"
	DirectionCredit = "credit"
)

// Статусы резерва.
const (
	ReservationActive    = "active"
	ReservationCommitted = "committed"
	ReservationReleased  = "released"
)

// Account — счёт. Currency фиксируется при создании счёта (в этой фазе
// счета создаются вне контракта wallet.v1 — см. ADR 0014, раздел
// «чего сознательно нет») и не меняется: счёт в одной валюте не может
// «переехать» в другую, не потеряв смысл истории проводок по нему.
type Account struct {
	ID        int64
	OwnerID   int64
	Currency  string
	CreatedAt time.Time
}

// LedgerEntry — одна проводка. Immutable по определению: если объект
// появился, у него нет операций изменения, только выставление ID.
//
// AmountCents — всегда положительное число. Знак операции задаёт
// Direction, а не отрицательные суммы: с отрицательными суммами SUM по
// debit и credit пришлось бы всё равно по-разному интерпретировать в
// зависимости от направления, а так это ровно один CASE в единственном
// месте (см. adapters/pg — вычисление баланса).
type LedgerEntry struct {
	ID          string
	AccountID   int64
	AmountCents int64
	Direction   string // debit | credit
	// OperationID объединяет ПАРУ проводок одной операции (например, обе
	// стороны CommitFunds). Без него по таблице невозможно ответить на
	// вопрос «а где вторая нога этой проводки» без угадывания по сумме
	// и времени.
	OperationID string
	// Reason — машиночитаемая причина: "order_payment" и подобные,
	// та же категория, что в wallet.account.debited (proto/gosplash/events).
	Reason string
	// ReferenceID — id резерва (или иной сущности), которая породила эту
	// проводку. Ссылка для разбора инцидентов: «эта проводка — от какого
	// именно резерва».
	ReferenceID string
	CreatedAt   time.Time
}

// Reservation — резерв. НЕ проводка: деньги ещё не двигались, просто
// часть баланса счёта временно недоступна для новых резервов.
//
// available = SUM(проводок по счёту) − SUM(активных резервов по счёту).
// Резерв существует ровно для того, чтобы вычесть эту сумму из available
// БЕЗ того, чтобы фактически перекладывать деньги — на этапе ReserveFunds
// ещё неизвестно, состоится ли покупка (CommitFunds) или её отменят
// (ReleaseFunds), а значит и проводку писать рано: append-only книга не
// прощает записи «на всякий случай», которые потом придётся отменять
// компенсирующей проводкой без всякой на то причины, кроме as if.
type Reservation struct {
	ID          string
	AccountID   int64
	AmountCents int64
	Currency    string
	Status      string // active | committed | released
	// IdempotencyKey — уникален в таблице резервов: именно на него
	// опирается идемпотентность ReserveFunds (см. adapters/pg).
	IdempotencyKey string
	// AvailableAfterCents — снимок available СРАЗУ ПОСЛЕ создания резерва.
	// Хранится, а не пересчитывается заново при повторном (идемпотентном)
	// вызове ReserveFunds: к моменту повтора баланс мог уже измениться
	// другими операциями, а правило идемпотентности требует вернуть ТОТ ЖЕ
	// ответ, что и в первый раз, а не текущий пересчитанный.
	AvailableAfterCents int64
	CreatedAt           time.Time
}

// Balance — то, что показывает GetBalance.
type Balance struct {
	AccountID int64
	Currency  string
	Available int64
	Reserved  int64
}

// AccountDebitedEvent — данные для wallet.account.debited (proto/gosplash/
// events/v1). Отдельный тип, а не eventsv1.AccountDebited: domain не имеет
// права импортировать gen/go (см. заголовок пакета), сборка protobuf-
// сообщения — забота adapters/pg, у которого уже есть право знать про outbox
// и Kafka-конверты.
type AccountDebitedEvent struct {
	AccountID   int64
	AmountCents int64
	Currency    string
	Reason      string
	ReferenceID string
}
