package domain

import "errors"

// Доменные ошибки — переменные, сравниваются через errors.Is (docs/STYLE.md).
// Ни одна из них не знает про gRPC: перевод в codes.* — работа адаптера
// internal/adapters/grpc/errors.go, ровно как в services/catalog.
var (
	// ErrAccountNotFound — счёт не заведён. В этой фазе счета не создаются
	// через wallet.v1 (см. ADR 0014) — ошибка означает либо опечатку в
	// account_id, либо ещё не заведённый в БД счёт.
	ErrAccountNotFound = errors.New("счёт не найден")

	// ErrInsufficientFunds — available меньше запрошенной суммы резерва.
	// Это FailedPrecondition, а не Internal: запрос корректен по форме,
	// но состояние счёта на текущий момент не позволяет его выполнить —
	// вызывающий может обоснованно решить, что делать дальше (не ретраить
	// молча, а сообщить покупателю «на счету не хватает денег»).
	ErrInsufficientFunds = errors.New("недостаточно средств")

	// ErrCurrencyMismatch — валюта операции не совпадает с валютой счёта
	// (ReserveFunds) или валюты двух счетов операции различаются
	// (CommitFunds: покупатель и автор). Конвертация в проекте не делается
	// (задача фазы 3 явно это запрещает) — несовпадение отвергается, а не
	// молча приводится к одной валюте по случайному курсу.
	ErrCurrencyMismatch = errors.New("операция между счетами в разных валютах запрещена")

	// ErrInvalidAmount — сумма операции должна быть положительным числом
	// копеек. Ноль или отрицательное число — это не «резерв на всякий
	// случай», а сломанный вызывающий код: 0.1+0.2 здесь не проблема
	// (деньги — int64), но неотрицательность суммы — тоже часть контракта,
	// которую стоит проверять явно, а не полагаться на то, что она удержит
	// инвариант «сумма проводок равна нулю» сама по себе (удержит, но ценой
	// проводок вида «списали минус пять рублей», что не имеет физического
	// смысла).
	ErrInvalidAmount = errors.New("сумма операции должна быть положительной")

	// ErrEmptyIdempotencyKey — без ключа идемпотентности операция не может
	// быть безопасно повторена (docs/STYLE.md, proto: «повтор с тем же
	// ключом возвращает тот же результат»), а без ключа даже определить,
	// что это повтор, нечем.
	ErrEmptyIdempotencyKey = errors.New("idempotency_key обязателен")

	// ErrReservationNotFound — резерва с таким id нет: неверный
	// reservation_id, либо резерв никогда не создавался.
	ErrReservationNotFound = errors.New("резерв не найден")

	// ErrReservationAlreadyCommitted — попытка ОСВОБОДИТЬ (Release) резерв,
	// который уже ПОДТВЕРЖДЁН (Commit): деньги уже списаны и зачислены,
	// откатывать нечего, а тихий успех замаскировал бы реальную ошибку саги
	// (звонок Release после успешного Commit — это её баг, а не штатный
	// повтор, см. ADR 0014 и services/wallet/internal/app/service.go).
	ErrReservationAlreadyCommitted = errors.New("резерв уже подтверждён — компенсация невозможна")

	// ErrReservationAlreadyReleased — попытка ПОДТВЕРДИТЬ (Commit) резерв,
	// который уже ОСВОБОЖДЁН (Release): те деньги уже вернулись в available
	// другой операцией, подтверждать нечего.
	ErrReservationAlreadyReleased = errors.New("резерв уже освобождён — подтверждать нечего")
)
