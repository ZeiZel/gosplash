package es

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
)

// Курсор — это ровно то, что Elasticsearch вернул в поле "sort" последнего
// показанного документа, закодированное в base64. Никакой собственной
// структуры не изобретается специально: search_after ожидает МАССИВ
// значений сортировки как есть, и единственная задача курсора — довезти
// его от одного HTTP-ответа до следующего HTTP-запроса через клиента,
// который не должен знать, что внутри (proto.SearchRequest.cursor — просто
// string).
//
// PATTERN: keyset-пагинация (search_after), а не from+size.
//
// from+size(=N) на глубокой странице заставляет КАЖДЫЙ шард отсортировать
// и вернуть координатору N ПЕРВЫХ документов целиком — координатор потом
// сам вырежет нужный кусок и выбросит остальное. Запрос 100-й страницы по
// 20 документов — это from=1980, и каждый шард обязан прогнать сортировку
// по 2000 документам, чтобы отдать 20; практический потолок в ES —
// index.max_result_window — не случайно равен 10 000 по умолчанию, именно
// из-за этой цены. search_after устраняет её: имея координаты последнего
// увиденного документа, каждый шард продолжает сортировку С ЭТОЙ ТОЧКИ,
// а не сначала — независимо от того, какая это по счёту страница.
//
// tie-breaker по listing_id ОБЯЗАТЕЛЕН в sort вместе с _score: _score —
// вещественное число, и у двух разных документов оно вполне может совпасть
// (особенно когда query пуст и все документы получают одинаковый
// match_all-скор). Без второго, гарантированно уникального поля в
// сортировке search_after не может однозначно определить "строго после
// какой точки продолжать" — документы с одинаковым _score на границе
// страницы либо задвоятся на соседних страницах, либо пропадут, в
// зависимости от того, как их разложит очередной запрос. listing_id
// уникален всегда, поэтому паре (_score, listing_id) всегда есть однозначное
// "следующий после" (почему не служебное _id — см. query_builder.go).
func encodeCursor(sortValues []any) (string, error) {
	raw, err := json.Marshal(sortValues)
	if err != nil {
		return "", fmt.Errorf("кодирование курсора: %w", err)
	}
	return base64.RawURLEncoding.EncodeToString(raw), nil
}

// decodeCursor возвращает nil без ошибки для пустой строки — это первая
// страница, у неё ещё нет search_after.
func decodeCursor(cursor string) ([]any, error) {
	if cursor == "" {
		return nil, nil
	}
	raw, err := base64.RawURLEncoding.DecodeString(cursor)
	if err != nil {
		return nil, fmt.Errorf("битый курсор: %w", err)
	}
	var values []any
	if err := json.Unmarshal(raw, &values); err != nil {
		return nil, fmt.Errorf("битый курсор: %w", err)
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("битый курсор: пустой набор значений сортировки")
	}
	return values, nil
}
