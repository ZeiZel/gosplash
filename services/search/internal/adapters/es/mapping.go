// Package es — адаптер к Elasticsearch: явный маппинг индекса, консьюмер
// (bulk-запись), поиск (построение запроса и разбор ответа).
package es

// indexMapping — тело запроса PUT /<индекс>, которым индекс создаётся.
//
// НЕОЧЕВИДНОЕ РЕШЕНИЕ (и обязательный по заданию разбор): почему НИКАКОГО
// dynamic mapping.
//
// Без явного маппинга Elasticsearch выводит тип поля из ПЕРВОГО документа,
// который в него попал, и это решение — окончательное: поле, однажды
// типизированное как text, никогда не станет числом без пересоздания
// индекса. На практике это значит: если первая карточка, случайно или
// намеренно, придёт с price_cents в виде строки "1500" (баг сериализации,
// ручной curl во время отладки — неважно), Elasticsearch заведёт price_cents
// как text. Все ПОСЛЕДУЮЩИЕ документы с price_cents:1500 (числом) будут
// проиндексированы нормально — но range-фильтр `price_cents: {gte: 1000}`
// перестанет работать вообще, потому что диапазонные операторы для text
// не определены, и это выяснится не при индексации (она пройдёт успешно!),
// а тихо, в проде, когда фильтр по цене начнёт возвращать пустоту или падать
// с ошибкой, для отладки которой придётся идти смотреть маппинг руками.
// "dynamic": "strict" ниже переворачивает это: КАЖДОЕ поле обязано быть
// описано заранее, а документ с незнакомым или не совпадающим по типу полем
// Elasticsearch ОТКЛОНЯЕТ сразу, кодом 400 (mapper_parsing_exception/
// strict_dynamic_mapping_exception) — то есть ошибка становится видна
// в момент записи, а не в момент фильтрации через полгода.
//
// text vs keyword — второй источник путаницы, который явный маппинг снимает
// раз и навсегда:
//
//	text    — анализируется: строка режется на токены анализатором
//	          (лоуркейс, стемминг, стоп-слова), и ищется соответствие ПО
//	          ТОКЕНАМ. "Закаты над морем" находится по запросу "закат":
//	          стеммер russian привёл оба слова к одной основе. Обратная
//	          сторона: text НЕЛЬЗЯ агрегировать и сортировать без явного
//	          .keyword-подполя — токенов много и непонятно, по какому
//	          из них сортировать.
//	keyword — НЕ анализируется: хранится и ищется как есть, целиком,
//	          байт в байт. "Закат" не найдёт "закаты" и наоборот. Зато
//	          keyword — единственное, что можно агрегировать (facets по
//	          tag_facets ниже), сортировать и фильтровать через term/terms
//	          ТОЧНО, без "почти совпало".
//
// Отсюда и выбор ниже: tags — только keyword (это категории, точное
// совпадение — единственный осмысленный поиск по ним, "закат" не должен
// находить карточки с тегом "закаты"); title и author_name — text, потому
// что по названию карточки и имени автора ищут словами, а не точным
// совпадением строки; author_name ДОПОЛНИТЕЛЬНО получает keyword-подполе —
// не для полнотекстового поиска, а на будущее (точная фильтрация/агрегация
// по автору без придумывания второго текстового поля).
//
// title — мультиполе с двумя стеммерами (russian, english), а не один
// анализатор на выбор. Зачем: стеммер приводит слово к основе ДО индексации
// ("закатами" → "закат", "sunsets" → "sunset") — без него запрос "закат"
// не находил бы "закаты", хотя это очевидно один и тот же смысл для
// человека. Но стеммер для русского и стеммер для английского — это разные
// алгоритмы, обученные на морфологии конкретного языка; применить russian
// к английскому названию (или наоборот) даст мусорную основу и не найдёт
// ничего. Каталог фотостока разноязычный: заголовок карточки может быть
// на любом из двух языков, и мультиполе индексирует его ОБОИМИ стеммерами
// одновременно (title.russian, title.english) — запрос ищет по всем трём
// вариантам сразу (adapters/es/query_builder.go), и хотя бы один совпадёт
// независимо от языка заголовка. Цена — троекратный расход места на это
// поле, оправданный тем, что заголовков на порядки меньше, чем, например,
// событий просмотра.
const indexMapping = `{
  "settings": {
    "number_of_shards": 1,
    "number_of_replicas": 0
  },
  "mappings": {
    "dynamic": "strict",
    "properties": {
      "listing_id": {"type": "keyword"},
      "title": {
        "type": "text",
        "fields": {
          "russian": {"type": "text", "analyzer": "russian"},
          "english": {"type": "text", "analyzer": "english"}
        }
      },
      "tags": {"type": "keyword"},
      "author_id": {"type": "long"},
      "author_name": {
        "type": "text",
        "fields": {
          "keyword": {"type": "keyword"}
        }
      },
      "price_cents": {"type": "integer"},
      "currency": {"type": "keyword"},
      "status": {"type": "keyword"},
      "published_at": {"type": "date"}
    }
  }
}`
